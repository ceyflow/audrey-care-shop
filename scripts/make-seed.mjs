// Generates supabase/seed.sql from js/data.js so the website and the database start identical.
//   node scripts/make-seed.mjs
// Re-running is safe: products and variants are upserted by id.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { window: {} };
vm.runInNewContext(readFileSync(join(root, 'js/data.js'), 'utf8'), ctx);
const { products } = ctx.window.AC_DATA;

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `'{${(a || []).map((x) => `"${String(x).replace(/(["\\])/g, '\\$1')}"`).join(',')}}'`;

let sql = '-- Generated by scripts/make-seed.mjs from js/data.js. Sample products: replace with your real catalogue.\n\n';
products.forEach((p, i) => {
  sql += `insert into public.products (id, kind, fragrance, name, badge, tagline, description, how_to_use, images, sort)\n` +
    `values (${q(p.id)}, ${q(p.kind)}, ${q(p.fragrance)}, ${q(p.name)}, ${q(p.badge)}, ${q(p.tagline)}, ${q(p.description)}, ${q(p.how_to_use)}, ${arr(p.images)}, ${i})\n` +
    `on conflict (id) do update set kind = excluded.kind, fragrance = excluded.fragrance, name = excluded.name, badge = excluded.badge,\n` +
    `  tagline = excluded.tagline, description = excluded.description, how_to_use = excluded.how_to_use, images = excluded.images, sort = excluded.sort;\n`;
  p.variants.forEach((v, j) => {
    sql += `insert into public.variants (id, product_id, label, price_lkr, compare_at_lkr, sort)\n` +
      `values (${q(v.id)}, ${q(p.id)}, ${q(v.label)}, ${v.price}, ${v.compare_at ?? 'null'}, ${j})\n` +
      `on conflict (id) do update set label = excluded.label, price_lkr = excluded.price_lkr, compare_at_lkr = excluded.compare_at_lkr, sort = excluded.sort;\n`;
  });
  sql += '\n';
});

writeFileSync(join(root, 'supabase/seed.sql'), sql);
console.log(`Wrote supabase/seed.sql (${products.length} products)`);
